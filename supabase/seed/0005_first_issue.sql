## 우드톤과 키 컬러 세 가지

바탕은 흰 회벽과 나무입니다. 나무는 오크나 미송처럼 노란기가 도는 쪽이어야 붉은 벽돌과 싸우지 않습니다. 월넛처럼 붉은 나무를 쓰면 벽돌과 색이 겹쳐 둘 다 죽습니다.

키 컬러는 셋이면 충분합니다.

- **쪽빛** — 옆집 기와와 하늘에 이미 있는 색입니다. 현관문과 벽 한 면에만 씁니다.
- **치자색** — 노란기가 도는 황토색. 주방 타일과 조명 갓 같은 작은 면에 씁니다. 벽돌과 같은 계열이라 부딪히지 않습니다.
- **먹색** — 이미 창틀에 들어가 있습니다. 선반 프레임과 손잡이까지 먹색으로 통일하면 집 전체의 선이 하나로 잡힙니다.

셋 모두 색면으로 씁니다. 벽 전체를 칠하는 색이 아니라 한 면, 한 가구에만 들어가는 색입니다.

선룸에는 평상을 깝니다. 창 쪽으로 낮게 짜고 아래를 책장으로 비웁니다. 좌식이면 창틀이 눈높이 아래로 내려가고, 그러면 마당이 액자처럼 보입니다. 여름 햇빛은 대나무 발로 막습니다. 발은 장식이 아니라 실제로 일을 하는 동양 요소입니다.

